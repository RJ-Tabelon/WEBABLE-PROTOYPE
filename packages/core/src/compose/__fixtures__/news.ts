/**
 * A news article with ads (hand-written, modelled on a mid-size newspaper):
 * a leaderboard ad above the masthead, section navigation, an article whose
 * paragraphs are interleaved with ad slots and a newsletter box, a share
 * toolbar, a comments section, a "Most read" rail with a sticky ad and an
 * autoplaying video ad, a fixed subscription bar, a support chat bubble and
 * a consent banner. Region keys (`ck`) let tests pass rule or Jev verdicts.
 */

const para = (y: number, chars: number, h = 120, links = 0): FxNode => ({
  t: 'p',
  k: 'text',
  b: [160, y, 680, h],
  fs: 18,
  tx: { chars, ...(links ? { links } : {}) },
});

const adSlot = (y: number, h: number, ck: string): FxNode => ({
  t: 'div',
  k: 'group',
  b: [160, y, 680, h],
  f: ['adhint'],
  ck,
  c: [
    {
      t: 'span',
      k: 'stext',
      b: [160, y, 120, 16],
      fs: 11,
      l: 'Advertisement',
    },
    { t: 'iframe', k: 'media', b: [210, y + 20, 580, h - 24], f: ['adhint'] },
  ],
});

const shareButton = (x: number, l: string): FxNode => ({
  t: 'button',
  k: 'control',
  b: [x, 900, 36, 36],
  fs: 14,
  f: ['icon'],
  l,
});

