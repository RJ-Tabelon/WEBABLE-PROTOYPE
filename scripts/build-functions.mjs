#!/usr/bin/env node
// Bundle @webable/core (and zod) for the Supabase Edge Functions.
//
//   pnpm build:functions             write supabase/functions/_shared/core.bundle.js
//   pnpm build:functions --check     fail when the committed bundle is stale
//   pnpm build:functions --no-types  skip the declaration check (faster)
//
// Why a bundle: Deno cannot load the workspace sources directly (bare `zod`
// imports, extensionless relative paths, pnpm symlinks), and the functions must
// run the exact same catalog, vocabulary and Jev client as the extension. The
// entry is supabase/functions/_shared/core-entry.ts; the output is plain ESM
// with no imports, so it also runs in Node (scripts/jev-mock-server.mjs).
//
// The output is formatted with the repo's Prettier config, so it passes
// `pnpm format:check` and rebuilds produce readable diffs.
//
// Types: core.bundle.js starts with `// @ts-self-types="./core.bundle.d.ts"`,
// a hand-maintained declaration file. Both modes type-check core-entry.ts and
// assert, with tsc, that every declaration matches the real export (same value
// names, mutually assignable types, no `any`). Exit codes: 0 ok, 1 stale or
// type drift, 2 the build itself failed.

import { spawnSync } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';
import * as prettier from 'prettier';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CORE_DIR = join(ROOT, 'packages/core');
const CORE_SRC = join(CORE_DIR, 'src');
const SHARED = join(ROOT, 'supabase/functions/_shared');
const ENTRY = join(SHARED, 'core-entry.ts');
const OUT = join(SHARED, 'core.bundle.js');
const DTS = join(SHARED, 'core.bundle.d.ts');
const TSC = join(CORE_DIR, 'node_modules/typescript/bin/tsc');

const rel = (p) => relative(ROOT, p).split('\\').join('/');

const BANNER = [
  '// @ts-self-types="./core.bundle.d.ts"',
  `// GENERATED by scripts/build-functions.mjs from ${rel(ENTRY)}. Do not edit.`,
  '// Rebuild with `pnpm build:functions`; `pnpm build:functions --check` fails when stale.',
].join('\n');

/**
 * Resolve `@webable/core/<module>` to packages/core/src/<module>.ts. Every core
 * module is side-effect free (package.json "sideEffects": false), so modules
 * whose exports are unused are dropped entirely.
 */
const coreSource = {
  name: 'webable-core-source',
  setup(b) {
    b.onResolve({ filter: /^@webable\/core(\/.*)?$/ }, (args) => {
      const sub = args.path.slice('@webable/core'.length) || '/index';
      return { path: join(CORE_SRC, `${sub.slice(1)}.ts`), sideEffects: false };
    });
  },
};

/**
 * Core imports the `z` namespace, which re-exports every zod locale (about 60
 * modules, about 40% of the bundle). The functions only use zod's default
 * English messages, and never report them to clients, so the locale index is
 * replaced with one that re-exports `en` alone. `z.locales` keeps working for
 * English; nothing else changes.
 */
const zodEnglishOnly = {
  name: 'zod-english-only',
  setup(b) {
    b.onLoad(
      { filter: /[\\/]zod[\\/]v4[\\/]locales[\\/]index\.js$/ },
      (args) => ({
        contents: 'export { default as en } from "./en.js";\n',
        loader: 'js',
        resolveDir: dirname(args.path),
      }),
    );
  },
};

async function bundle() {
  const result = await build({
    absWorkingDir: ROOT,
    entryPoints: [ENTRY],
    outfile: OUT,
    write: false,
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    mainFields: ['module', 'main'],
    // core-entry.ts imports zod itself; resolve it from @webable/core so the
    // bundle carries exactly one copy, the version core is tested against.
    nodePaths: [join(CORE_DIR, 'node_modules')],
    charset: 'utf8',
    legalComments: 'inline',
    banner: { js: BANNER },
    logLevel: 'silent',
    plugins: [coreSource, zodEnglishOnly],
  });
  const file = result.outputFiles.find((f) => f.path === OUT);
  if (!file) throw new Error('esbuild produced no output file.');
  // Format with the repo's Prettier config so `pnpm format:check` passes on the
  // committed file and diffs between builds stay readable.
  const options = (await prettier.resolveConfig(OUT)) ?? {};
  const text = await prettier.format(file.text, { ...options, filepath: OUT });
  return { text, warnings: result.warnings };
}

// ---------------------------------------------------------------------------
// Declaration check: core.bundle.d.ts must describe core-entry.ts exactly.
// ---------------------------------------------------------------------------

/** Declared type name -> the real type, as an expression over `E` (core-entry) and `W` (wire/api types). */
const TYPE_PAIRS = {
  DecideRequest: 'W.DecideRequest',
  DecideResponse: 'W.DecideResponse',
  DecideOk: 'Extract<W.DecideResponse, { ok: true }>',
  DecideDegraded: 'Extract<W.DecideResponse, { ok: false }>',
  DegradedReason: 'W.DegradedReason',
  RegionAnswer: 'W.RegionAnswer',
  RegionEvidence: 'P.RegionEvidence',
  PageContext: 'P.PageContext',
  PageCategory: 'P.PageCategory',
  RegionRole: 'P.RegionRole',
  BuiltQuestions: 'C.BuiltQuestions',
  JsonValue: 'A.JsonValue',
  JevEntry: 'A.JevEntry',
  JevState: 'A.JevState',
  JevQuestion: 'A.JevQuestion',
  JevModelId: 'A.JevModelId',
  JevRequest: 'A.JevRequest',
  JevAnswer: 'A.JevAnswer',
  JevResponse: 'A.JevResponse',
  JevFailure: 'A.JevFailure',
  JevResult: 'A.JevResult',
  CallJevOptions: 'J.CallJevOptions',
  MockJevOptions: 'M.MockJevOptions',
  MockJevFetchOptions: 'M.MockJevFetchOptions',
  OpId: 'O.OpId',
  VerifyCode: 'T.VerifyCode',
  AggReport: 'z.infer<typeof E.aggReportSchema>',
};

function conformanceSource(tmp) {
  const imp = (p) => {
    const r = relative(tmp, p).split('\\').join('/');
    return r.startsWith('.') ? r : `./${r}`;
  };
  const core = (m) => imp(join(CORE_SRC, m));
  const pairs = Object.entries(TYPE_PAIRS)
    .map(
      ([name, real]) =>
        `type _${name} = Assert<Same<D.${name}, ${real}>>;\n` +
        `type _${name}NotAny = Assert<NotAny<D.${name}>>;`,
    )
    .join('\n');
  return `// Generated by scripts/build-functions.mjs. Checks core.bundle.d.ts against core-entry.ts.
import type { z } from 'zod';
import type * as E from '${imp(ENTRY.replace(/\.ts$/, ''))}';
import type * as D from '${imp(OUT)}';
import type * as W from '${core('decide/wire')}';
import type * as C from '${core('decide/catalog')}';
import type * as M from '${core('decide/mock')}';
import type * as A from '${core('jev/api')}';
import type * as J from '${core('jev/client')}';
import type * as P from '${core('page/types')}';
import type * as O from '${core('ops/catalog')}';
import type * as T from '${core('policy/types')}';

type Assert<T extends true> = T;
type IsAny<T> = 0 extends 1 & T ? true : false;
type NotAny<T> = IsAny<T> extends true ? false : true;
type Same<A, B> = IsAny<A> extends true ? false : IsAny<B> extends true ? false
  : [A] extends [B] ? ([B] extends [A] ? true : false) : false;

// The declaration file names exactly the runtime exports.
type _Keys = Assert<Same<keyof typeof E, keyof typeof D>>;

// Every declared type equals the real one.
${pairs}

// Every runtime export satisfies its declaration.
declare const e: typeof E;
export const values: { [K in keyof typeof D]: (typeof D)[K] } = e;
`;
}

function runTsc(args) {
  const res = spawnSync(process.execPath, [TSC, ...args], {
    cwd: ROOT,
    encoding: 'utf8',
  });
  if (res.error) throw res.error;
  return { status: res.status ?? 1, output: `${res.stdout}${res.stderr}` };
}

async function checkDeclarations() {
  const tmp = await mkdtemp(join(tmpdir(), 'webable-functions-'));
  try {
    const tsconfig = {
      compilerOptions: {
        target: 'ES2022',
        module: 'ESNext',
        moduleResolution: 'Bundler',
        lib: ['ES2023', 'DOM', 'DOM.Iterable'],
        types: [],
        strict: true,
        noUncheckedIndexedAccess: true,
        noEmit: true,
        // The hand-written .d.ts must be checked itself: an unresolved name in
        // it would otherwise become `any` and pass every comparison.
        skipLibCheck: false,
        paths: {
          '@webable/core/*': [join(CORE_SRC, '*')],
          zod: [join(CORE_DIR, 'node_modules/zod')],
        },
      },
      files: [ENTRY, DTS, join(tmp, 'conformance.ts')],
    };
    await writeFile(join(tmp, 'tsconfig.json'), JSON.stringify(tsconfig));
    await writeFile(join(tmp, 'conformance.ts'), conformanceSource(tmp));
    const { status, output } = runTsc(['-p', join(tmp, 'tsconfig.json')]);
    // tsc prints paths relative to the repo root; show the generated file as <check>.
    const tidy = output
      .split(relative(ROOT, tmp))
      .join('<check>')
      .split(tmp)
      .join('<check>');
    return { ok: status === 0, output: tidy };
  } finally {
    await rm(tmp, { recursive: true, force: true });
  }
}

async function main() {
  const args = new Set(process.argv.slice(2).filter((a) => a !== '--'));
  for (const a of args) {
    if (a !== '--check' && a !== '--no-types') {
      console.error(`Unknown argument: ${a}`);
      process.exit(2);
    }
  }
  const check = args.has('--check');

  let out;
  try {
    out = await bundle();
  } catch (error) {
    const errors = error?.errors ?? [];
    for (const e of errors) {
      const where = e.location
        ? `${e.location.file}:${e.location.line}:${e.location.column} `
        : '';
      console.error(`${where}${e.text}`);
    }
    if (errors.length === 0)
      console.error(error instanceof Error ? error.message : String(error));
    process.exit(2);
  }
  for (const w of out.warnings) console.warn(`warning: ${w.text}`);

  let failed = false;
  const committed = await readFile(OUT, 'utf8').catch(() => null);
  const kb = (Buffer.byteLength(out.text) / 1024).toFixed(1);
  if (check) {
    if (committed === out.text) {
      console.log(`${rel(OUT)} is up to date (${kb} KB).`);
    } else {
      console.error(
        committed === null
          ? `${rel(OUT)} is missing. Run \`pnpm build:functions\`.`
          : `${rel(OUT)} is stale. Run \`pnpm build:functions\` and commit the result.`,
      );
      failed = true;
    }
  } else if (committed === out.text) {
    console.log(`${rel(OUT)} unchanged (${kb} KB).`);
  } else {
    await writeFile(OUT, out.text);
    console.log(`Wrote ${rel(OUT)} (${kb} KB).`);
  }

  if (!args.has('--no-types')) {
    const types = await checkDeclarations();
    if (types.ok) {
      console.log(`${rel(DTS)} matches ${rel(ENTRY)}.`);
    } else {
      console.error(
        `${rel(DTS)} does not match ${rel(ENTRY)}:\n${types.output.trim()}`,
      );
      failed = true;
    }
  }

  process.exit(failed ? 1 : 0);
}

await main();
