// Generates packages/core/src/db/types.ts from the live schema without Docker.
// Usage: node scripts/gen-db-types.mjs   (reads SUPABASE_DIRECT_URL from .env)
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import 'dotenv/config';
import pg from 'pg';

const url = (process.env.SUPABASE_DIRECT_URL ?? '').replace(':6543/', ':5432/');
if (!url) {
  console.error('SUPABASE_DIRECT_URL is not set.');
  process.exit(1);
}

const client = new pg.Client({ connectionString: url });
await client.connect();

const scalar = (udt) => {
  switch (udt) {
    case 'uuid':
    case 'text':
    case 'varchar':
    case 'bpchar':
    case 'date':
    case 'timestamptz':
    case 'timestamp':
    case 'time':
    case 'bytea':
      return 'string';
    case 'int2':
    case 'int4':
    case 'int8':
    case 'float4':
    case 'float8':
    case 'numeric':
      return 'number';
    case 'bool':
      return 'boolean';
    case 'json':
    case 'jsonb':
      return 'Json';
    case 'void':
      return 'undefined';
    default:
      return null;
  }
};

const enums = (
  await client.query(`
    select t.typname::text as name, array_agg(e.enumlabel::text order by e.enumsortorder) as labels
    from pg_type t join pg_enum e on e.enumtypid = t.oid
    join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public' group by t.typname order by t.typname`)
).rows;
const enumNames = new Set(enums.map((e) => e.name));
const tsType = (udt) =>
  scalar(udt) ??
  (enumNames.has(udt) ? `Database['public']['Enums']['${udt}']` : 'unknown');

const columns = (
  await client.query(`
    select c.table_name, c.column_name, c.udt_name, c.is_nullable = 'YES' as nullable,
           c.column_default is not null or c.is_identity = 'YES' as has_default
    from information_schema.columns c
    join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
    where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
    order by c.table_name, c.ordinal_position`)
).rows;

const tables = new Map();
for (const col of columns) {
  if (!tables.has(col.table_name)) tables.set(col.table_name, []);
  tables.get(col.table_name).push(col);
}

const functions = (
  await client.query(`
    select p.proname as name,
           coalesce(p.proargnames::text[], '{}') as arg_names,
           coalesce(array(select format_type(unnest(p.proargtypes), null)), '{}') as arg_types,
           p.pronargdefaults as n_defaults,
           p.proretset as returns_set,
           format_type(p.prorettype, null) as return_type,
           rt.typname as return_udt,
           rt.typtype as return_kind,
           pg_get_function_result(p.oid) as result_sig
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    join pg_type rt on rt.oid = p.prorettype
    where n.nspname = 'public' and p.prokind = 'f'
    order by p.proname`)
).rows;

const formatToUdt = {
  uuid: 'uuid',
  text: 'text',
  jsonb: 'jsonb',
  json: 'json',
  bigint: 'int8',
  integer: 'int4',
  smallint: 'int2',
  boolean: 'bool',
  date: 'date',
  'timestamp with time zone': 'timestamptz',
};

const rowType = (cols, indent) =>
  cols
    .map(
      (c) =>
        `${indent}${c.column_name}: ${tsType(c.udt_name)}${c.nullable ? ' | null' : ''}`,
    )
    .join('\n');
const insertType = (cols, indent, allOptional) =>
  cols
    .map(
      (c) =>
        `${indent}${c.column_name}${allOptional || c.nullable || c.has_default ? '?' : ''}: ${tsType(c.udt_name)}${c.nullable ? ' | null' : ''}`,
    )
    .join('\n');

let out = `// Generated by scripts/gen-db-types.mjs from the live schema. Do not edit.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
`;
for (const [name, cols] of tables) {
  out += `      ${name}: {
        Row: {
${rowType(cols, '          ')}
        };
        Insert: {
${insertType(cols, '          ', false)}
        };
        Update: {
${insertType(cols, '          ', true)}
        };
        Relationships: [];
      };
`;
}
out += `    };
    Views: { [_ in never]: never };
    Functions: {
`;
for (const fn of functions) {
  // proargnames also lists OUT/TABLE columns; proargtypes lists inputs only.
  fn.arg_names = fn.arg_names.slice(0, fn.arg_types.length);
  const required = fn.arg_names.length - fn.n_defaults;
  const args = fn.arg_names.length
    ? `{ ${fn.arg_names
        .map(
          (argName, i) =>
            `${argName}${i >= required ? '?' : ''}: ${tsType(formatToUdt[fn.arg_types[i]] ?? fn.arg_types[i])}`,
        )
        .join('; ')} }`
    : 'Record<PropertyKey, never>';
  let returns;
  if (fn.result_sig.startsWith('TABLE(')) {
    const inner = fn.result_sig.slice(6, -1);
    const fields = inner.split(',').map((part) => {
      const [field, ...typeParts] = part.trim().split(' ');
      return `${field}: ${tsType(formatToUdt[typeParts.join(' ')] ?? typeParts.join(' '))}`;
    });
    returns = `{ ${fields.join('; ')} }[]`;
  } else if (fn.return_kind === 'c') {
    returns = `Database['public']['Tables']['${fn.return_udt}']['Row']`;
  } else {
    returns = tsType(fn.return_udt);
  }
  out += `      ${fn.name}: { Args: ${args}; Returns: ${returns} };\n`;
}
out += `    };
    Enums: {
${enums.map((e) => `      ${e.name}: ${e.labels.map((l) => `'${l}'`).join(' | ')};`).join('\n')}
    };
    CompositeTypes: { [_ in never]: never };
  };
};

type PublicSchema = Database['public'];
export type Tables<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Row'];
export type TablesInsert<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Insert'];
export type TablesUpdate<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Update'];
export type Enums<T extends keyof PublicSchema['Enums']> = PublicSchema['Enums'][T];
`;

await client.end();
const target = resolve('packages/core/src/db/types.ts');
await writeFile(target, out);
console.log(
  `Wrote ${target} (${tables.size} tables, ${functions.length} functions).`,
);
